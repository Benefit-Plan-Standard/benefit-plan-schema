// Accumulator slots in schema order: [slot, deductible or MOOP column suffix, embedded column suffix, network].
const DEDUCTIBLE_SLOTS = [
  ['individual_deductible', 'DedInnTier1Individual', null, 'in-network'],
  ['family_deductible', 'DedInnTier1FamilyPerGroup', 'DedInnTier1FamilyPerPerson', 'in-network'],
];
const MOOP_SLOTS = [
  ['individual_oop_max', 'InnTier1IndividualMOOP', null, 'in-network'],
  ['family_oop_max', 'InnTier1FamilyPerGroupMOOP', 'InnTier1FamilyPerPersonMOOP', 'in-network'],
];
const OON_DEDUCTIBLE_SLOTS = [
  ['oon_individual_deductible', 'DedOutOfNetIndividual', null, 'out-of-network'],
  ['oon_family_deductible', 'DedOutOfNetFamilyPerGroup', 'DedOutOfNetFamilyPerPerson', 'out-of-network'],
];
const OON_MOOP_SLOTS = [
  ['oon_individual_oop_max', 'OutOfNetIndividualMOOP', null, 'out-of-network'],
  ['oon_family_oop_max', 'OutOfNetFamilyPerGroupMOOP', 'OutOfNetFamilyPerPersonMOOP', 'out-of-network'],
];

// Medical (MEHB) columns unless the plan says medical and drug are integrated, or
// the medical columns are empty and only the combined (TEHB) columns carry values.
function accumulatorPrefix(plan, kind) {
  const integrated = (kind === 'deductible' ? plan.MedicalDrugDeductiblesIntegrated : plan.MedicalDrugMaximumOutofPocketIntegrated) === 'Yes';
  const slots = kind === 'deductible' ? [...DEDUCTIBLE_SLOTS, ...OON_DEDUCTIBLE_SLOTS] : [...MOOP_SLOTS, ...OON_MOOP_SLOTS];
  const hasValues = (prefix) => slots.some(([, col]) => {
    const r = parseDollars(plan[prefix + col] || '');
    return !r.error && r.value !== null;
  });
  if (integrated) return { prefix: 'TEHB', reason: 'integrated' };
  if (hasValues('MEHB') || !hasValues('TEHB')) return { prefix: 'MEHB', reason: 'medical' };
  return { prefix: 'TEHB', reason: 'combined-only' };
}

function buildAccumulators(plan, errors) {
  const out = {};
  const ded = accumulatorPrefix(plan, 'deductible');
  const moop = accumulatorPrefix(plan, 'moop');
  const add = ([slot, col, embeddedCol, network], choice) => {
    const r = parseDollars(plan[choice.prefix + col] || '');
    if (r.error) { errors.push(`${choice.prefix + col}: ${r.error}`); return; }
    if (r.value === null) return;
    const a = { amount: r.value, currency: 'USD', network_tier: network };
    a.applies_to = choice.prefix === 'TEHB' ? 'integrated' : 'medical';
    if (embeddedCol) {
      const raw = (plan[choice.prefix + embeddedCol] || '').trim();
      const e = parseDollars(raw);
      if (e.error) errors.push(`${choice.prefix + embeddedCol}: ${e.error}`);
      else if (e.value !== null) a.embedded = true;
      else if (/not applicable$/i.test(raw)) a.embedded = false;
    }
    out[slot] = a;
  };
  for (const s of DEDUCTIBLE_SLOTS) add(s, ded);
  for (const s of MOOP_SLOTS) add(s, moop);
  for (const s of OON_DEDUCTIBLE_SLOTS) add(s, ded);
  for (const s of OON_MOOP_SLOTS) add(s, moop);
  return { accumulators: out, ded, moop };
}

// Every non-blank accumulator cell, verbatim, in header order.
function accumulatorCells(plan, header) {
  return header
    .filter((h) => /^(M|D|T)EHB/.test(h) && (plan[h] || '').trim() !== '')
    .map((h) => `${h} "${plan[h].trim()}"`);
}

// ---- benefits -------------------------------------------------------------------------
const CROSSWALK_BY_NAME = new Map(CROSSWALK.map.map((r) => [r.puf_benefit_name, r]));

const TIER_COLUMNS = {
  IN: ['CopayInnTier1', 'CoinsInnTier1'],
  IN2: ['CopayInnTier2', 'CoinsInnTier2'],
  OUT: ['CopayOutofNet', 'CoinsOutofNet'],
};

function hasValue(s) {
  return !NO_STEP.has((s || '').trim());
}

function planHasTier2(benefitRows) {
  return benefitRows.some((r) => hasValue(r.CopayInnTier2) || hasValue(r.CoinsInnTier2));
}

function idFromName(s) {
  return s.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

function coveredFlag(row) {
  const v = row.IsCovered.trim();
  if (v === 'Covered') return true;
  if (v === 'Not Covered' || v === '') return false;
  throw new Error(`unreadable IsCovered "${row.IsCovered}"`);
}

function moopFlag(raw) {
  const v = (raw || '').trim();
  if (v === 'Yes') return false;
  if (v === 'No') return true;
  return null;
}

function tierRow(row, tierId, covered, errors) {
  const [copayCol, coinsCol] = TIER_COLUMNS[tierId];
  const copay = row[copayCol] || '';
  const coins = row[coinsCol] || '';
  const blank = copay.trim() === '' && coins.trim() === '';
  if (covered && blank) return null;
  const notes = `PUF ${copayCol} "${copay.trim()}"; ${coinsCol} "${coins.trim()}"`;
  if (!covered) {
    const out = { tier_id: tierId, covered: false, cost_shares: [] };
    if (!blank) out.notes = notes;
    return out;
  }
  const moop = moopFlag(tierId === 'OUT' ? row.IsExclFromOonMOOP : row.IsExclFromInnMOOP);
  const steps = [];
  for (const [raw, column] of [[copay, 'copay'], [coins, 'coinsurance']]) {
    const r = parseCostShare(raw, column);
    if (r.error) { errors.push(`${tierId}: ${r.error}`); continue; }
    if (!r.step) continue;
    const cs = { type: r.step.type, sequence: steps.length + 1 };
    if ('amount' in r.step) cs.amount = r.step.amount;
    if ('rate' in r.step) cs.rate = r.step.rate;
    if (r.step.basis) cs.basis = r.step.basis;
    cs.applies_to_deductible = r.step.applies_to_deductible;
    if (moop !== null) cs.applies_to_moop = moop;
    if (WORDING_NOTES[r.wording]) cs.notes = WORDING_NOTES[r.wording];
    steps.push(cs);
  }
  return { tier_id: tierId, covered: true, cost_shares: steps, notes };
}

function buildBenefit(row, x, tiers, errors) {
  let covered;
  try { covered = coveredFlag(row); } catch (e) { errors.push(e.message); return null; }
  const network_cost_shares = tiers.map((t) => tierRow(row, t, covered, errors)).filter(Boolean);
  const limits = [];
  const l = parseLimit(row.LimitQty || '', row.LimitUnit || '');
  if (l.error) errors.push(l.error);
  else if (l.limit) limits.push(l.limit);
  else if ((row.QuantLimitOnSvc || '').trim() === 'Yes') errors.push('QuantLimitOnSvc is "Yes" but LimitQty and LimitUnit are blank');
  const conditions = [];
  if ((row.Exclusions || '').trim()) conditions.push({ type: 'exclusion', description: row.Exclusions.trim() });
  if ((row.Explanation || '').trim()) conditions.push({ type: 'explanation', description: row.Explanation.trim() });
  return {
    benefit_id: idFromName(row.BenefitName),
    benefit_type: x.category === 'PHARMACY' ? 'pharmacy' : 'medical',
    category: x.category,
    service_name: row.BenefitName,
    canonical_key: x.canonical_key,
    raw_label: row.BenefitName,
    network_cost_shares,
    limits,
    conditions,
  };
}

// ---- document --------------------------------------------------------------------------
function planIdFor(plan) {
  const part = (s) => idFromName(s.replace(/\([^)]*\)/g, ' '));
  let id = [part(plan.IssuerMarketPlaceMarketingName), part(plan.PlanMarketingName)].filter(Boolean).join('_');
  while (id.length > 64) id = id.slice(0, id.lastIndexOf('_'));
  return id;
}

function sourceExcerpt(plan, source) {
  const y = plan.BusinessYear;
  return `CMS Health Insurance Exchange Public Use Files, plan year ${y}: Plan Attributes PUF (${source.planFile}, ` +
    `from ${PUF_DOWNLOAD}${y}/plan-attributes-puf.zip) and Benefits and Cost Sharing PUF (${source.benefitsFile}, ` +
    `from ${PUF_DOWNLOAD}${y}/benefits-and-cost-sharing-puf.zip), downloaded ${source.downloaded}. ` +
    `HIOS plan ID ${plan.PlanId} (the Benefit Plan Standard v1.1.0 schema has no identifier field, so the ID is recorded here). ` +
    `SBC URL from the Plan Attributes PUF: ${(plan.URLForSummaryofBenefitsCoverage || '').trim() || '(blank)'}.`;
}

function accumulatorExcerpt(plan, header, ded, moop) {
  const said = (c) => (c.reason === 'integrated'
    ? 'the plan states they are integrated, so the combined medical and drug (TEHB) columns are used'
    : c.reason === 'combined-only'
      ? 'the file carries combined medical and drug (TEHB) values only, so those are used'
      : 'the medical (MEHB) columns are used');
  return `Accumulators from the Plan Attributes PUF. Deductibles: MedicalDrugDeductiblesIntegrated ` +
    `"${plan.MedicalDrugDeductiblesIntegrated}"; ${said(ded)}. Out-of-pocket maximums: MedicalDrugMaximumOutofPocketIntegrated ` +
    `"${plan.MedicalDrugMaximumOutofPocketIntegrated}"; ${said(moop)}. Every non-blank accumulator cell, verbatim: ` +
    `${accumulatorCells(plan, header).join('; ')}.`;
}

function attributesExcerpt(plan) {
  const cells = UNCARRIED_ATTRIBUTES
    .filter((c) => (plan[c] || '').trim() !== '')
    .map((c) => `${c} "${plan[c].trim()}"`);
  return `Plan Attributes PUF values with no Benefit Plan Standard v1.1.0 field, verbatim: ${cells.join('; ')}.`;
}

function unmappedExcerpt(unmapped) {
  if (unmapped.length === 0) return null;
  const list = unmapped.map((u) => `${u.name} (${u.status}${u.inCrosswalk ? '' : '; not in the crosswalk'})`);
  return `Benefits and Cost Sharing PUF rows for this plan whose BenefitName has no canonical_key in ` +
    `fhir/marketplace-puf-crosswalk.json, not emitted as benefits (${unmapped.length}): ${list.join('; ')}.`;
}

/**
 * plan:        the Plan Attributes row (object keyed by header)
 * planHeader:  the Plan Attributes header, in file order
 * rows:        the Benefits and Cost Sharing rows for the same PlanId, in file order
 * source:      { planFile, benefitsFile, downloaded }
 * Returns { doc, errors }. When errors is non-empty, doc is null.
 */
function buildDocument(plan, planHeader, rows, source) {
  const errors = [];
  const market = MARKETS[plan.MarketCoverage];
  if (!market) errors.push(`unknown MarketCoverage "${plan.MarketCoverage}"`);
  if (plan.DentalOnlyPlan === 'Yes') errors.push('the plan is a stand-alone dental plan; the importer covers medical plans');
  const seen = new Set();
  for (const r of rows) {
    if (seen.has(r.BenefitName)) errors.push(`BenefitName "${r.BenefitName}" appears twice for ${plan.PlanId}`);
    seen.add(r.BenefitName);
  }
  if (rows.length === 0) errors.push(`no Benefits and Cost Sharing rows for ${plan.PlanId}`);

  const tier2 = planHasTier2(rows);
  const tiers = tier2 ? ['IN', 'IN2', 'OUT'] : ['IN', 'OUT'];
  const network_tiers = tier2
    ? [
      { tier_id: 'IN', name: 'In-Network Tier 1', description: 'Benefits and Cost Sharing PUF columns CopayInnTier1 and CoinsInnTier1' },
      { tier_id: 'IN2', name: 'In-Network Tier 2', description: 'Benefits and Cost Sharing PUF columns CopayInnTier2 and CoinsInnTier2' },
    ]
    : [{ tier_id: 'IN', name: 'In-Network', description: 'Benefits and Cost Sharing PUF columns CopayInnTier1 and CoinsInnTier1' }];
  network_tiers.push({ tier_id: 'OUT', name: 'Out-of-Network', description: 'Benefits and Cost Sharing PUF columns CopayOutofNet and CoinsOutofNet' });

  const { accumulators, ded, moop } = buildAccumulators(plan, errors);

  const benefits = [];
  const unmapped = [];
  for (const r of rows) {
    const x = CROSSWALK_BY_NAME.get(r.BenefitName);
    if (!x || !x.canonical_key) {
      let status;
      try { status = coveredFlag(r) ? 'Covered' : 'Not Covered'; } catch (e) { status = `IsCovered "${r.IsCovered}"`; }
      unmapped.push({ name: r.BenefitName, status, inCrosswalk: Boolean(x) });
      continue;
    }
    const berr = [];
    const b = buildBenefit(r, x, tiers, berr);
    for (const e of berr) errors.push(`benefit "${r.BenefitName}": ${e}`);
    if (b) benefits.push(b);
  }

  let effective = null;
  let expiry = null;
  try {
    effective = isoDate(plan.PlanEffectiveDate || '');
    expiry = isoDate(plan.PlanExpirationDate || '');
  } catch (e) { errors.push(e.message); }

  if (errors.length) return { doc: null, errors };

  const doc = {};
  doc.plan_id = planIdFor(plan);
  doc.plan_name = plan.PlanMarketingName.trim();
  doc.carrier = plan.IssuerMarketPlaceMarketingName.trim();
  if (plan.PlanType.trim()) doc.plan_type = PLAN_TYPES[plan.PlanType.trim()] || plan.PlanType.trim();
  doc.plan_year = Number(plan.BusinessYear);
  if (effective) doc.effective_date = effective;
  if (expiry) doc.expiry_date = expiry;
  doc.market = market;
  doc.network_tiers = network_tiers;
  doc.accumulators = accumulators;
  doc.benefits = benefits;
  doc.source_references = [
    sourceExcerpt(plan, source),
    attributesExcerpt(plan),
    accumulatorExcerpt(plan, planHeader, ded, moop),
    unmappedExcerpt(unmapped),
  ].filter(Boolean).map((excerpt) => ({ excerpt }));
  doc.schema_version = SCHEMA_VERSION;
  return { doc, errors: [] };
}

function serialize(doc) {
  return JSON.stringify(doc, null, 2) + '\n';
}

function fileSlug(doc) {
  return doc.plan_id.toLowerCase().replace(/_/g, '-');
}

// ---- reading the public files ------------------------------------------------------------
function pufFiles(dataDir, year) {
  const dir = path.join(dataDir, String(year));
  if (!fs.existsSync(dir)) throw new Error(`no folder ${path.relative(REPO_ROOT, dir)}; download the plan year ${year} files first (see the spec, section 11)`);
  const csvs = fs.readdirSync(dir).filter((f) => /\.csv$/i.test(f));
  const pick = (re, label) => {
    const hits = csvs.filter((f) => re.test(f));
    if (hits.length !== 1) throw new Error(`expected one ${label} CSV in ${path.relative(REPO_ROOT, dir)}, found ${hits.length}`);
    return path.join(dir, hits[0]);
  };
  return {
    dir,
    planFile: pick(/plan[-_ ]?attributes/i, 'Plan Attributes'),
    benefitsFile: pick(/benefits[-_ ]?(and[-_ ]?)?cost[-_ ]?sharing/i, 'Benefits and Cost Sharing'),
  };
}

function downloadDate(dir, override) {
  if (override) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(override)) throw new Error(`--downloaded must be YYYY-MM-DD, got "${override}"`);
    return override;
  }
  const manifest = path.join(dir, 'download.json');
  if (!fs.existsSync(manifest)) throw new Error(`no ${path.relative(REPO_ROOT, manifest)}; pass --downloaded YYYY-MM-DD`);
  const d = JSON.parse(fs.readFileSync(manifest, 'utf8')).downloaded;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d || '')) throw new Error(`${path.relative(REPO_ROOT, manifest)} has no "downloaded" date`);
  return d;
}

// A 14-character standard component ID resolves to its -01 variant (standard
// on-exchange) when present, else to its only variant. Spec section 5.1.
function resolvePlanRow(planRows, wanted) {
  const exact = planRows.filter((r) => r.PlanId === wanted);
  if (exact.length === 1) return exact[0];
  if (exact.length > 1) throw new Error(`PlanId ${wanted} appears ${exact.length} times in the Plan Attributes PUF`);
  const variants = planRows.filter((r) => r.StandardComponentId === wanted);
  if (variants.length === 0) throw new Error(`no plan ${wanted} in the Plan Attributes PUF`);
  const v01 = variants.find((r) => r.PlanId === wanted + '-01');
  if (v01) return v01;
  if (variants.length === 1) return variants[0];
  throw new Error(`${wanted} has ${variants.length} variants (${variants.map((r) => r.PlanId).join(', ')}) and no -01; give the full plan ID`);
}

async function readPlan(dataDir, year, wanted) {
  const files = pufFiles(dataDir, year);
  const planRows = [];
  let planHeader = null;
  const component = wanted.slice(0, 14);
  await streamCsv(files.planFile, (r) => {
    if (!planHeader) planHeader = Object.keys(r);
    if (r.StandardComponentId === component) planRows.push(r);
  });
  const plan = resolvePlanRow(planRows, wanted);
  const rows = [];
  await streamCsv(files.benefitsFile, (r) => { if (r.PlanId === plan.PlanId) rows.push(r); });
  return { plan, planHeader, rows, files };
}

// Everything buildDocument needs for one plan, read from the public files.
async function loadPlan({ dataDir = DATA_DIR, year, plan: wanted, downloaded }) {
  const { plan, planHeader, rows, files } = await readPlan(dataDir, year, wanted);
  if (String(plan.BusinessYear).trim() !== String(year)) throw new Error(`plan ${plan.PlanId} has BusinessYear ${plan.BusinessYear}, not ${year}`);
  const source = {
    planFile: path.basename(files.planFile),
    benefitsFile: path.basename(files.benefitsFile),
    downloaded: downloadDate(files.dir, downloaded),
  };
  return { plan, planHeader, rows, source };
}

async function importPlan(opts) {
  const { plan, planHeader, rows, source } = await loadPlan(opts);
  const { doc, errors } = buildDocument(plan, planHeader, rows, source);
  if (errors.length) throw new Error(`${plan.PlanId} cannot be imported:\n  ${errors.join('\n  ')}`);
  return doc;
}

async function listPlans({ dataDir = DATA_DIR, year, issuer, state }) {
  const files = pufFiles(dataDir, year);
  const out = [];
  await streamCsv(files.planFile, (r) => {
    if (r.IssuerId === issuer && (!state || r.StateCode === state.toUpperCase())) out.push(r);
  });
  out.sort((a, b) => (a.PlanId < b.PlanId ? -1 : a.PlanId > b.PlanId ? 1 : 0));
  return out;
}

// ---- schema check (local files, no network) ---------------------------------------------
function validateDocument(doc) {
  const Ajv2020 = require('ajv/dist/2020');
  const ajv = new Ajv2020({ allErrors: true, strict: false });
  try { require('ajv-formats')(ajv); } catch (e) { /* optional */ }
  const schema = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'schema', 'v' + SCHEMA_VERSION, 'benefit-plan.schema.json'), 'utf8'));
  const validate = ajv.compile(schema);
  return validate(doc) ? [] : validate.errors.map((e) => `${e.instancePath || '(root)'} ${e.message}`);
}

// ---- CLI ------------------------------------------------------------------------------------
async function main(argv) {
  const opt = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--year') opt.year = Number(argv[++i]);
    else if (a === '--plan') opt.plan = argv[++i];
    else if (a === '--out' || a === '-o') opt.out = argv[++i];
    else if (a === '--issuer') opt.issuer = argv[++i];
    else if (a === '--state') opt.state = argv[++i];
    else if (a === '--data') opt.dataDir = path.resolve(argv[++i]);
    else if (a === '--downloaded') opt.downloaded = argv[++i];
    else if (a === '--write-golden') opt.writeGolden = true;
    else if (a === '-h' || a === '--help') {
      console.log('usage: node scripts/from-marketplace-puf.js --year <YYYY> --plan <HIOS plan id> [--out <file>]\n' +
        '       node scripts/from-marketplace-puf.js --year <YYYY> --issuer <HIOS issuer id> [--state <ST>]\n' +
        '       node scripts/from-marketplace-puf.js --write-golden\n' +
        '       options: --data <dir> (default data/puf), --downloaded <YYYY-MM-DD>');
      return 0;
    } else {
      console.error(`error: unknown argument "${a}"`);
      return 1;
    }
  }
  try {
    if (opt.writeGolden) {
      for (const g of GOLDEN) {
        const doc = await importPlan({ dataDir: opt.dataDir, year: g.year, plan: g.plan });
        const errs = validateDocument(doc);
        if (errs.length) throw new Error(`${g.plan} output fails the schema:\n  ${errs.join('\n  ')}`);
        const target = path.join(EXAMPLES_DIR, fileSlug(doc) + '.puf.json');
        fs.writeFileSync(target, serialize(doc));
        console.log(`wrote ${path.relative(REPO_ROOT, target)}  (PY${g.year} ${g.plan})`);
      }
      return 0;
    }
    if (!opt.year) throw new Error('--year is required');
    if (opt.issuer) {
      const rows = await listPlans(opt);
      if (rows.length === 0) { console.log(`no plans for issuer ${opt.issuer}${opt.state ? ' in ' + opt.state : ''} in plan year ${opt.year}`); return 0; }
      for (const r of rows) {
        console.log([r.PlanId, r.StateCode, r.MarketCoverage, r.DentalOnlyPlan === 'Yes' ? 'Dental' : r.MetalLevel, r.PlanType,
          r.CSRVariationType, r.PlanVariantMarketingName || r.PlanMarketingName].join('\t'));
      }
      return 0;
    }
    if (!opt.plan) throw new Error('give --plan <HIOS plan id>, or --issuer <HIOS issuer id> to list plans');
    const doc = await importPlan(opt);
    const errs = validateDocument(doc);
    if (errs.length) throw new Error(`output fails the v${SCHEMA_VERSION} schema:\n  ${errs.join('\n  ')}`);
    const text = serialize(doc);
    if (opt.out) fs.writeFileSync(opt.out, text);
    else process.stdout.write(text);
    return 0;
  } catch (e) {
    console.error('error: ' + e.message);
    return 1;
  }
}

