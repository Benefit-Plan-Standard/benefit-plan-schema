// ---- CSV (RFC 4180), streamed -------------------------------------------------
// Quoted fields may hold commas, doubled quotes and line breaks. Records end at
// CRLF, LF or CR. A leading UTF-8 byte order mark is dropped. A quote inside an
// unquoted field is kept as text, and so is text after a closing quote.
const FIELD_START = 0;
const UNQUOTED = 1;
const QUOTED = 2;
const QUOTE_SEEN = 3;

class CsvParser {
  constructor(onRecord) {
    this.onRecord = onRecord;
    this.field = '';
    this.record = [];
    this.state = FIELD_START;
    this.skipLF = false;
    this.first = true;
  }

  emit() {
    const r = this.record;
    this.record = [];
    if (r.length === 1 && r[0] === '') return; // blank line
    this.onRecord(r);
  }

  write(s) {
    let i = 0;
    const n = s.length;
    if (this.first) {
      this.first = false;
      if (s.charCodeAt(0) === 0xfeff) i = 1;
    }
    while (i < n) {
      if (this.state === QUOTED) {
        const q = s.indexOf('"', i);
        if (q === -1) { this.field += s.slice(i); return; }
        this.field += s.slice(i, q);
        i = q + 1;
        this.state = QUOTE_SEEN;
        continue;
      }
      if (this.state === QUOTE_SEEN) {
        if (s.charCodeAt(i) === 34) { this.field += '"'; i++; this.state = QUOTED; continue; }
        this.state = UNQUOTED;
      }
      const c = s.charCodeAt(i);
      if (this.skipLF) {
        this.skipLF = false;
        if (c === 10) { i++; continue; }
      }
      if (this.state === FIELD_START && c === 34) { this.state = QUOTED; i++; continue; }
      let j = i;
      while (j < n) {
        const d = s.charCodeAt(j);
        if (d === 44 || d === 10 || d === 13) break;
        j++;
      }
      this.field += s.slice(i, j);
      this.state = UNQUOTED;
      if (j === n) return;
      const d = s.charCodeAt(j);
      this.record.push(this.field);
      this.field = '';
      this.state = FIELD_START;
      if (d !== 44) {
        this.emit();
        if (d === 13) this.skipLF = true;
      }
      i = j + 1;
    }
  }

  end() {
    if (this.state === QUOTED) throw new Error('CSV ends inside a quoted field');
    if (this.state !== FIELD_START || this.record.length) {
      this.record.push(this.field);
      this.field = '';
      this.emit();
    }
  }
}

// Calls onRow(object) for each data row, keyed by the header names. A row whose
// field count differs from the header is an error.
async function streamCsv(file, onRow) {
  let header = null;
  let line = 1;
  const parser = new CsvParser((r) => {
    if (!header) { header = r.map((h) => h.trim()); return; }
    line++;
    if (r.length !== header.length) {
      throw new Error(`${path.basename(file)}: record ${line} has ${r.length} fields, the header has ${header.length}`);
    }
    const row = {};
    for (let k = 0; k < header.length; k++) row[header[k]] = r[k];
    onRow(row);
  });
  const stream = fs.createReadStream(file, { encoding: 'utf8', highWaterMark: 1 << 20 });
  for await (const chunk of stream) parser.write(chunk);
  parser.end();
}

// ---- cost-share strings ---------------------------------------------------------
// The grammar is in docs/specs/marketplace-puf-importer.md section 6. A string
// outside it is unreadable: the caller reports it, quoted, and writes nothing.
const AMOUNT = '\\$((?:\\d{1,3}(?:,\\d{3})+|\\d+)(?:\\.\\d{1,2})?)';
const RATE = '(\\d{1,3}(?:\\.\\d+)?)%';
const COPAY_RE = new RegExp(`^${AMOUNT}(?: Copay(?: per (Day|Stay))?(?: (after|with|before) deductible)?)?$`);
const COINS_RE = new RegExp(`^${RATE}(?: Coinsurance (after) deductible)?$`);
const NO_CHARGE_RE = /^No Charge(?: (after) deductible)?$/;
const NO_STEP = new Set(['', 'Not Applicable']);

function toAmount(s) {
  return Number(s.replace(/,/g, ''));
}

function toRate(s) {
  return Number((Number(s) / 100).toFixed(6));
}

// column: 'copay' or 'coinsurance'. Returns { step } (step null when the string
// states no cost-share step) or { error }.
function parseCostShare(raw, column) {
  const s = raw.trim();
  if (NO_STEP.has(s)) return { step: null };
  const type = column === 'copay' ? 'copay' : 'coinsurance';
  let m = NO_CHARGE_RE.exec(s);
  if (m) {
    const step = { type };
    if (type === 'copay') step.amount = 0;
    else step.rate = 0;
    step.applies_to_deductible = m[1] === 'after';
    return { step, wording: m[1] || null };
  }
  if (column === 'copay') {
    m = COPAY_RE.exec(s);
    if (!m) return { error: `unreadable copay string "${raw}"` };
    const step = { type, amount: toAmount(m[1]) };
    if (m[2]) step.basis = 'per_' + m[2].toLowerCase();
    step.applies_to_deductible = Boolean(m[3]);
    return { step, wording: m[3] || null };
  }
  m = COINS_RE.exec(s);
  if (!m) return { error: `unreadable coinsurance string "${raw}"` };
  const rate = toRate(m[1]);
  if (rate > 1) return { error: `coinsurance over 100% in "${raw}"` };
  return { step: { type, rate, applies_to_deductible: Boolean(m[2]) }, wording: m[2] || null };
}

const WORDING_NOTES = {
  with: 'PUF wording "with deductible": the copay applies and the deductible also applies; not the same as "after deductible".',
  before: 'PUF wording "before deductible" (plan years 2014 to 2017): the copay applies before the deductible is met; the deductible also applies.',
};

// ---- limits -------------------------------------------------------------------------
// LimitUnit is "<thing> per <period>" (for example "Visit(s) per Year") or, in
// older files, "Lifetime <thing>".
function limitThing(s) {
  const t = s.toLowerCase().replace(/\(s\)$/, '');
  return t.endsWith('s') ? t : t + 's';
}

function parseLimit(qtyRaw, unitRaw) {
  const qty = qtyRaw.trim();
  const unit = unitRaw.trim();
  if (!qty && !unit) return { limit: null };
  if (!/^\d+(\.\d+)?$/.test(qty)) return { error: `unreadable LimitQty "${qtyRaw}" (LimitUnit "${unitRaw}")` };
  let m = /^([A-Za-z]+(?:\(s\))?) per ((?:\d+ )?[A-Za-z]+(?: [A-Za-z]+)?)$/.exec(unit);
  let type;
  let period;
  if (m) {
    type = limitThing(m[1]);
    period = 'per_' + m[2].toLowerCase().replace(/ /g, '_');
  } else if ((m = /^Lifetime ([A-Za-z]+)$/.exec(unit))) {
    type = limitThing(m[1]);
    period = 'per_lifetime';
  } else {
    return { error: `unreadable LimitUnit "${unitRaw}" (LimitQty "${qtyRaw}")` };
  }
  return { limit: { type, value: Number(qty), period } };
}

// ---- plan attributes ----------------------------------------------------------------
// Dollar cells read "$6,000 ", "$12000 per group" or "$0 per person"; absent
// values read "Not Applicable", "per group not applicable" or are blank.
function parseDollars(raw) {
  const s = raw.trim();
  if (s === '' || /not applicable$/i.test(s)) return { value: null };
  const m = /^\$((?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d{1,2})?)(?: per (?:person|group))?$/.exec(s);
  if (!m) return { error: `unreadable dollar amount "${raw}"` };
  return { value: toAmount(m[1]) };
}

function isoDate(raw) {
  const s = raw.trim();
  if (s === '') return null;
  let m = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec(s);
  if (m) return `${m[3]}-${m[1].padStart(2, '0')}-${m[2].padStart(2, '0')}`;
  m = /^(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if (m) return `${m[1]}-${m[2]}-${m[3]}`;
  throw new Error(`unreadable date "${raw}"`);
}

