#!/usr/bin/env node
/**
 * CMS Marketplace public use files to Benefit Plan Standard importer
 *
 * Reads the Plan Attributes PUF and the Benefits and Cost Sharing PUF that CMS
 * publishes for each plan year (Health Insurance Exchange public use files) and
 * writes one Benefit Plan Standard v1.1.0 document for one plan. It writes BPS
 * JSON only; FHIR comes from scripts/to-insuranceplan.js reading this output.
 * Spec: docs/specs/marketplace-puf-importer.md
 *
 * The public files are not in the repository. Put them in data/puf/<year>/
 * (git-ignored), unzipped, with a download.json that records the download date.
 *
 * buildDocument() is a pure function: no network, no clock, no randomness. The
 * same rows always give byte-identical output.
 *
 * Usage:
 *   node scripts/from-marketplace-puf.js --year 2026 --plan <HIOS plan id> --out <file>
 *   node scripts/from-marketplace-puf.js --year 2026 --issuer <HIOS issuer id> --state <ST>
 *   node scripts/from-marketplace-puf.js --write-golden      regenerate the examples/*.puf.json files
 *   options: --data <dir> (default data/puf), --downloaded <YYYY-MM-DD> (default from download.json)
 *
 * Exit codes: 0 = written or listed, 1 = error (nothing is written).
 */

