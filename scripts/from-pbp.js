#!/usr/bin/env node
/**
 * CMS Plan Benefit Package (PBP) Benefits to Benefit Plan Standard importer
 *
 * Reads the PBP Benefits files that CMS publishes for each contract year
 * (Medicare Advantage) and writes one Benefit Plan Standard v1.2.0 document for
 * one plan. It writes BPS JSON only. Spec: docs/specs/pbp-importer.md; file
 * layout: docs/specs/pbp-record-layout-notes.md.
 *
 * It writes the plan level (identity, plan type, service area, plan year, premium
 * and Part B premium reduction, member services phone and website, deductibles,
 * out-of-pocket maximums, network tiers with the provider directory link) and the benefits named in
 * fhir/pbp-crosswalk.json (the workgroup MVP), with cost shares per network
 * tier, ranges, day intervals, limits and coverage. From the Part D files it writes
 * the pharmacy object and the Part D benefits of a plan with drug coverage, and a
 * document of its own for a stand-alone Medicare Prescription Drug Plan (PDP);
 * mapping: docs/specs/pbp-part-d-mapping.md.
 *
 * The files are not in the repository. Put them in data/pbp/<year>/ (git-ignored),
 * unzipped, with a download.json that records the download date. The golden
 * plans' rows are committed in test/fixtures/pbp/<year>/ for the test.
 *
 * buildDocument() is a pure function: no network, no clock, no randomness.
 *
 * Usage:
 *   node scripts/from-pbp.js --year 2027 --plan H2406-013-000 [--out <file>]
 *   node scripts/from-pbp.js --year 2027 --contract H2406        list the contract's plans
 *   node scripts/from-pbp.js --write-golden                       regenerate examples/*.pbp.json (needs data/pbp/)
 *   node scripts/from-pbp.js --write-fixtures                     re-cut test/fixtures/pbp/ (needs data/pbp/)
 *   options: --data <dir> (default data/pbp), --downloaded <YYYY-MM-DD> (default from download.json)
 *
 * Exit codes: 0 = written or listed, 1 = error (nothing is written).
 */

