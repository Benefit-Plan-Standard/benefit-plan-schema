#!/usr/bin/env node
/**
 * Parse report for the Benefits and Cost Sharing PUF
 *
 * Runs the importer's own cost-share and limit parsers (scripts/from-marketplace-puf.js)
 * over every row of one plan year's Benefits and Cost Sharing PUF and writes a
 * Markdown report: every distinct cost-share string, how often it occurs, and how
 * the parser reads it, with the unreadable strings in their own table.
 *
 * Usage:
 *   node scripts/puf-parse-report.js                       PY2026, writes docs/specs/marketplace-puf-parse-report.md
 *   node scripts/puf-parse-report.js --year 2023 --out <file.md>
 *   options: --data <dir> (default data/puf)
 *
 * The output depends only on the input file: no dates, no clock.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { streamCsv, parseCostShare, parseLimit, pufFiles, DATA_DIR } = require('./from-marketplace-puf.js');

const REPO_ROOT = path.resolve(__dirname, '..');
const COLUMNS = [
  ['CopayInnTier1', 'copay', 'tier1'], ['CopayInnTier2', 'copay', 'tier2'], ['CopayOutofNet', 'copay', 'oon'],
  ['CoinsInnTier1', 'coinsurance', 'tier1'], ['CoinsInnTier2', 'coinsurance', 'tier2'], ['CoinsOutofNet', 'coinsurance', 'oon'],
];

const byCount = (a, b) => b.total - a.total || (a.text < b.text ? -1 : a.text > b.text ? 1 : 0);
const fmt = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const cell = (s) => (s === '' ? '(blank)' : '`' + s.replace(/\|/g, '\\|').replace(/`/g, "'") + '`');

function reading(r) {
  if (r.error) return { type: 'unreadable', value: '', deductible: '', basis: '' };
  if (!r.step) return { type: 'no step', value: '', deductible: '', basis: '' };
  const s = r.step;
  const value = s.type === 'copay' ? `amount ${s.amount}` : `rate ${s.rate}`;
  const deductible = String(s.applies_to_deductible) + (r.wording ? ` ("${r.wording} deductible")` : '');
  return { type: s.type, value, deductible, basis: s.basis || '' };
}

async function main(argv) {
  let year = 2026;
  let out = path.join(REPO_ROOT, 'docs', 'specs', 'marketplace-puf-parse-report.md');
  let dataDir = DATA_DIR;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--year') year = Number(argv[++i]);
    else if (argv[i] === '--out') out = path.resolve(argv[++i]);
    else if (argv[i] === '--data') dataDir = path.resolve(argv[++i]);
    else { console.error(`error: unknown argument "${argv[i]}"`); return 1; }
  }
  const files = pufFiles(dataDir, year);
  const strings = new Map();
  const units = new Map();
  const covered = new Map();
  let rows = 0;
  const plans = new Set();
  await streamCsv(files.benefitsFile, (row) => {
    rows++;
    plans.add(row.PlanId);
    for (const [col, family, where] of COLUMNS) {
      const text = row[col];
      const key = family + '\u0000' + text;
      let e = strings.get(key);
      if (!e) {
        e = { family, text, total: 0, tier1: 0, tier2: 0, oon: 0, r: parseCostShare(text, family) };
        strings.set(key, e);
      }
      e.total++;
      e[where]++;
    }
    const ukey = row.LimitQty.trim() === '' && row.LimitUnit.trim() === '' ? '' : row.LimitUnit;
    let u = units.get(ukey);
    if (!u) { u = { text: ukey, total: 0, sample: row.LimitQty, r: null }; units.set(ukey, u); }
    u.total++;
    const lr = parseLimit(row.LimitQty, row.LimitUnit);
    if (lr.error) u.error = (u.error || 0) + 1;
    else if (!u.r && lr.limit) u.r = lr.limit;
    covered.set(row.IsCovered, (covered.get(row.IsCovered) || 0) + 1);
  });

  const all = [...strings.values()].sort(byCount);
  const unreadable = all.filter((e) => e.r.error);
  const cellsTotal = all.reduce((n, e) => n + e.total, 0);
  const unreadableCells = unreadable.reduce((n, e) => n + e.total, 0);
  const rel = (p) => path.relative(REPO_ROOT, p).replace(/\\/g, '/');

  const L = [];
  L.push(`# Marketplace PUF parse report, plan year ${year}`);
  L.push('');
  L.push(`Generated by \`node scripts/puf-parse-report.js${year === 2026 ? '' : ' --year ' + year}\` from \`${path.basename(files.benefitsFile)}\` ` +
    `(Benefits and Cost Sharing PUF, ${rel(files.dir)}/). It runs the importer's own parser, \`parseCostShare\` and \`parseLimit\` in ` +
    '`scripts/from-marketplace-puf.js`, so each reading below is exactly what the importer writes. The grammar is in ' +
    '[`marketplace-puf-importer.md`](marketplace-puf-importer.md), section 6.');
  L.push('');
  L.push('## Summary');
  L.push('');
  L.push('| Item | Count |');
  L.push('|---|---|');
  L.push(`| Rows | ${fmt(rows)} |`);
  L.push(`| Plan variants (distinct PlanId) | ${fmt(plans.size)} |`);
  L.push(`| Cost-share cells read (6 per row) | ${fmt(cellsTotal)} |`);
  L.push(`| Distinct strings, copay columns | ${fmt(all.filter((e) => e.family === 'copay').length)} |`);
  L.push(`| Distinct strings, coinsurance columns | ${fmt(all.filter((e) => e.family === 'coinsurance').length)} |`);
  L.push(`| Distinct unreadable strings | ${fmt(unreadable.length)} |`);
  L.push(`| Cells holding an unreadable string | ${fmt(unreadableCells)} |`);
  L.push('');
  L.push('A string is counted once per column family: copay columns (`CopayInnTier1`, `CopayInnTier2`, `CopayOutofNet`) and ' +
    'coinsurance columns (`CoinsInnTier1`, `CoinsInnTier2`, `CoinsOutofNet`). The same text can read differently in the 2 ' +
    'families, because each family accepts only its own forms. "No step" means the string states no cost-share step ' +
    '(blank, or `Not Applicable`). The deductible flag is `applies_to_deductible`; the wording that set it is quoted.');
  L.push('');
  L.push('## Unreadable strings');
  L.push('');
  if (unreadable.length === 0) {
    L.push('None. Every cost-share string in the file is inside the grammar.');
  } else {
    L.push('| Count | Column family | String | Parser message |');
    L.push('|---|---|---|---|');
    for (const e of unreadable) L.push(`| ${fmt(e.total)} | ${e.family} | ${cell(e.text)} | ${e.r.error.replace(/\|/g, '\\|')} |`);
  }
  L.push('');
  L.push('## Every distinct string, by frequency');
  L.push('');
  L.push('Sorted by total count, highest first; ties by string.');
  L.push('');
  L.push('| Count | Tier 1 | Tier 2 | Out of network | Column family | String | Type | Amount or rate | Deductible flag | Basis |');
  L.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const e of all) {
    const x = reading(e.r);
    L.push(`| ${fmt(e.total)} | ${fmt(e.tier1)} | ${fmt(e.tier2)} | ${fmt(e.oon)} | ${e.family} | ${cell(e.text)} | ${x.type} | ${x.value} | ${x.deductible} | ${x.basis} |`);
  }
  L.push('');
  L.push('## Limit units');
  L.push('');
  L.push('`LimitUnit` values and the `limits[]` entry the parser writes for them (shown with one sample `LimitQty`). Sorted by count, highest first.');
  L.push('');
  L.push('| Count | LimitUnit | Sample LimitQty | type | period | Unreadable rows |');
  L.push('|---|---|---|---|---|---|');
  for (const u of [...units.values()].sort(byCount)) {
    if (u.text === '') { L.push(`| ${fmt(u.total)} | (no limit) | | | | 0 |`); continue; }
    L.push(`| ${fmt(u.total)} | ${cell(u.text)} | ${cell(u.sample)} | ${u.r ? u.r.type : ''} | ${u.r ? u.r.period : ''} | ${fmt(u.error || 0)} |`);
  }
  L.push('');
  L.push('## IsCovered');
  L.push('');
  L.push('| Count | IsCovered | Read as |');
  L.push('|---|---|---|');
  for (const [k, n] of [...covered].sort((a, b) => b[1] - a[1])) {
    L.push(`| ${fmt(n)} | ${cell(k)} | ${k === 'Covered' ? 'covered: true' : k === 'Not Covered' || k === '' ? 'covered: false' : 'unreadable'} |`);
  }
  L.push('');
  fs.writeFileSync(out, L.join('\n'));
  console.log(`wrote ${rel(out)}: ${all.length} distinct strings, ${unreadable.length} unreadable (${unreadableCells} cells)`);
  return 0;
}

main(process.argv.slice(2)).then((c) => process.exit(c), (e) => { console.error('error: ' + e.message); process.exit(1); });
