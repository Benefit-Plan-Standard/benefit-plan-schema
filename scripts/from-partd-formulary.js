#!/usr/bin/env node
/**
 * CMS monthly Part D formulary file to Benefit Plan Standard importer
 *
 * Reads the CMS public use file "Prescription Drug Plan Formulary and Pharmacy
 * Network Information" (the monthly zip, unzipped) and writes the drug lists of
 * Medicare Part D plans in Benefit Plan Standard v1.2.0 (draft 9): a formulary list
 * (schema/v1.2.0/formulary.schema.json) once per FORMULARY_ID, and a plan document
 * that is the Medicare Advantage importer's document for the same plan
 * (scripts/from-pbp.js) with pharmacy.formulary_reference and the plan's own
 * formulary items added. Spec and mapping: docs/specs/partd-formulary-importer.md.
 *
 * It reads Plan Information, Basic Drugs Formulary, Excluded Drugs Formulary,
 * Beneficiary Cost and Indication Based Coverage, and nothing else in the zip.
 * The files are not in the repository: put them in data/partd-formulary/<release>/txt/
 * under their names in the zip, with a download.json beside txt/ that records the
 * download date, the URLs and the SHA-256 of every file. The golden plans' rows are
 * committed in test/fixtures/partd-formulary/<release>/.
 *
 * The build is a pure function of the files: no network, no clock, no randomness.
 *
 * Usage:
 *   node scripts/from-partd-formulary.js --release 2027_20261008 --plan H2406-013-000 [--out <file>]
 *   node scripts/from-partd-formulary.js --release 2027_20261008 --formulary 00027002 [--out <file>]
 *   node scripts/from-partd-formulary.js --release 2027_20261008 --all --out-dir <dir>
 *   node scripts/from-partd-formulary.js --release 2027_20261008 --report [--out <file>]
 *   node scripts/from-partd-formulary.js --write-golden      regenerate examples/partd-formulary/ (needs data/)
 *   node scripts/from-partd-formulary.js --write-fixtures    re-cut test/fixtures/partd-formulary/ (needs data/)
 *   options: --data <dir> (default data/partd-formulary), --pbp-data <dir> (default data/pbp)
 *
 * Exit codes: 0 = written, 1 = error. --plan, --formulary and --report write nothing
 * on an error. --all writes into empty folders every list and every plan it can, lists
 * the refusals and the errors in its report, and exits 1 when a plan is an error;
 * --write-fixtures and --write-golden write file by file.
 */

