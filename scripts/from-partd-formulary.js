// ---- reading the files ------------------------------------------------------------------
// Pipe-delimited, CRLF, a header row, no quoting; Windows-1252 (Plan Information carries
// a few accented plan names, such as "Freedom Máximo (HMO-POS)"). A record whose field
// count differs from the header, or a header that is not the layout's, is an error.
const DECODER = new TextDecoder('windows-1252');

async function readPipe(file, spec, onRow) {
  const name = path.basename(file);
  let header = null;
  let line = 0;
  let carry = '';
  const handle = (rec) => {
    line++;
    if (/[\r\n]/.test(rec)) throw new Error(`${name}: line ${line} holds a line break that is not CRLF`);
    if (header === null) {
      header = rec;
      if (rec !== spec.header.join('|')) throw new Error(`${name}: the header is not the layout's (${SPEC} section 2):\n  file:   ${rec}\n  layout: ${spec.header.join('|')}`);
      return;
    }
    if (rec === '') return;
    const cells = rec.split('|');
    if (cells.length !== spec.header.length) throw new Error(`${name}: line ${line} has ${cells.length} fields, the header has ${spec.header.length}`);
    onRow(cells, rec, line);
  };
  for await (const chunk of fs.createReadStream(file, { highWaterMark: 1 << 20 })) {
    const parts = (carry + DECODER.decode(chunk)).split('\r\n');
    carry = parts.pop();
    for (const p of parts) handle(p);
  }
  if (carry !== '') handle(carry);
  if (header === null) throw new Error(`${name}: empty file`);
  return header;
}

function releaseDir(dataDir, release) {
  if (!/^\d{4}_\d{8}$/.test(release || '')) throw new Error(`--release must be the zip's name without .zip, as 2027_20261008; got "${release}"`);
  const dir = path.join(dataDir, release);
  if (!fs.existsSync(dir)) throw new Error(`no folder ${path.relative(REPO_ROOT, dir)}; download and unzip release ${release} first (${SPEC} section 2)`);
  const txt = fs.existsSync(path.join(dir, 'txt')) ? path.join(dir, 'txt') : dir;
  const names = fs.readdirSync(txt);
  const find = (spec) => {
    const hits = names.filter((f) => f.toLowerCase().endsWith('.txt') && f.toLowerCase().startsWith(spec.prefix) && !f.toLowerCase().includes('sample'));
    if (hits.length !== 1) throw new Error(`expected 1 file whose name starts with "${spec.prefix}" in ${path.relative(REPO_ROOT, txt)}, found ${hits.length}`);
    return path.join(txt, hits[0]);
  };
  const manifestFile = path.join(dir, 'download.json');
  if (!fs.existsSync(manifestFile)) throw new Error(`no ${path.relative(REPO_ROOT, manifestFile)}: record the download date, the URLs and the SHA-256 of every file (${SPEC} section 2)`);
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  if (!/^\d{4}-\d{2}-\d{2}$/.test(manifest.downloaded || '')) throw new Error(`${path.relative(REPO_ROOT, manifestFile)} has no "downloaded" date`);
  return { dir, txt, find, manifest };
}

// Reads the 5 files of a release into memory. Problems with 1 plan or 1 formulary are
// kept on it (errors), so that --all can refuse that plan and go on; a problem with a
// whole file throws.
async function loadRelease({ dataDir = DATA_DIR, release }) {
  const { dir, find, manifest } = releaseDir(dataDir, release);
  const rel = {
    release, dir, manifest,
    zip: `${release}.zip`,
    contractYear: Number(release.slice(0, 4)),
    posted: `${release.slice(5, 9)}-${release.slice(9, 11)}-${release.slice(11, 13)}`,
    names: {}, headers: {}, sha256: {},
    plans: new Map(), formularies: new Map(), excluded: new Map(), ibc: new Map(), cost: new Map(),
  };
  const zipUrl = (manifest.urls || []).find((u) => u.endsWith(rel.zip));
  if (!zipUrl) throw new Error(`download.json names no URL ending in ${rel.zip}`);
  rel.zipUrl = zipUrl;
  for (const kind of Object.keys(FILES)) {
    const file = find(FILES[kind]);
    rel.names[kind] = path.basename(file);
    rel.sha256[kind] = (manifest.sha256 || {})[rel.names[kind]];
    if (!/^[0-9a-f]{64}$/.test(rel.sha256[kind] || '')) throw new Error(`download.json has no SHA-256 for "${rel.names[kind]}"`);
    rel.headers[kind] = await readPipe(file, FILES[kind], (cells, raw, line) => addRow(rel, kind, cells, raw, line));
  }
  return rel;
}

const PLAN_SAME = ['CONTRACT_NAME', 'PLAN_NAME', 'FORMULARY_ID', 'PREMIUM', 'DEDUCTIBLE', 'SNP', 'PLAN_SUPPRESSED_YN'];

function addRow(rel, kind, cells, raw, line) {
  const row = { cells, raw, line };
  const c = COL[kind];
  if (kind === 'plan') {
    const key = `${cells[c.CONTRACT_ID]}-${cells[c.PLAN_ID]}-${cells[c.SEGMENT_ID]}`;
    let p = rel.plans.get(key);
    if (!p) {
      p = { key, first: row, rows: 0, errors: [] };
      if (!/^[HRS]\d{4}-\d{3}-\d{3}$/.test(key)) p.errors.push(`${rel.names.plan} line ${line}: the plan "${key}" is not CONTRACT_ID, PLAN_ID and SEGMENT_ID of 5, 3 and 3 characters`);
      if (!/^\d{8}$/.test(cells[c.FORMULARY_ID])) p.errors.push(`${rel.names.plan} line ${line}: FORMULARY_ID "${cells[c.FORMULARY_ID]}" is not 8 digits`);
      rel.plans.set(key, p);
    } else {
      for (const col of PLAN_SAME) {
        if (cells[c[col]] !== p.first.cells[c[col]]) {
          p.errors.push(`${rel.names.plan}: ${col} is "${p.first.cells[c[col]]}" on line ${p.first.line} and "${cells[c[col]]}" on line ${line} for the same plan`);
        }
      }
    }
    p.rows++;
  } else if (kind === 'basic') {
    const id = cells[c.FORMULARY_ID];
    let f = rel.formularies.get(id);
    if (!f) {
      f = { id, version: cells[c.FORMULARY_VERSION], year: cells[c.CONTRACT_YEAR], rows: [], byRxcui: new Map(), errors: [] };
      rel.formularies.set(id, f);
    }
    for (const [col, v] of [['FORMULARY_VERSION', f.version], ['CONTRACT_YEAR', f.year]]) {
      if (cells[c[col]] !== v) f.errors.push(`${rel.names.basic} line ${line}: ${col} "${cells[c[col]]}", where formulary ${id} has "${v}" on line ${f.rows[0].line}`);
    }
    const rx = cells[c.RXCUI].trim();
    if (f.byRxcui.has(rx)) f.errors.push(`${rel.names.basic} line ${line}: a second row for FORMULARY_ID "${id}", RXCUI "${rx}" (the first is line ${f.rows[f.byRxcui.get(rx)].line})`);
    else f.byRxcui.set(rx, f.rows.length);
    f.rows.push(row);
  } else if (kind === 'cost') {
    const key = `${cells[c.CONTRACT_ID]}-${cells[c.PLAN_ID]}-${cells[c.SEGMENT_ID]}`;
    if (!rel.cost.has(key)) rel.cost.set(key, []);
    rel.cost.get(key).push(row);
  } else {
    const key = `${cells[c.CONTRACT_ID]}-${cells[c.PLAN_ID]}`;
    if (!rel[kind].has(key)) rel[kind].set(key, []);
    rel[kind].get(key).push(row);
  }
}

// ---- cell rules (spec sections 5 and 6) -----------------------------------------------------
const YN = { Y: true, N: false };
const QL_01 = { 1: true, 0: false };
const NO_PERIOD_DAYS = 999;

function cite(rel, kind, row) {
  return { document: rel.zip, excerpt: `${rel.names[kind]}: ${row.raw}` };
}

function at(rel, kind, row, col) {
  return `${rel.names[kind]} line ${row.line}, ${col} "${row.cells[COL[kind][col]]}"`;
}

function flag(rel, kind, row, col, codes, errors) {
  const v = row.cells[COL[kind][col]];
  if (Object.prototype.hasOwnProperty.call(codes, v)) return codes[v];
  errors.push(`${at(rel, kind, row, col)} is not ${Object.keys(codes).map((k) => `"${k}"`).join(' or ')}`);
  return null;
}

function tierId(rel, kind, row, col, errors) {
  const v = row.cells[COL[kind][col]];
  if (!/^\d{1,2}$/.test(v) || Number(v) < 1) { errors.push(`${at(rel, kind, row, col)} is not a tier number from 1 to 99`); return null; }
  return `T${Number(v)}`;
}

function rxcuiOf(rel, kind, row, errors) {
  const v = row.cells[COL[kind].RXCUI].trim();
  if (!/^\d{1,8}$/.test(v)) errors.push(`${at(rel, kind, row, 'RXCUI')} is not an RxNorm concept id`);
  return v;
}

// QUANTITY_LIMIT_YN, _AMOUNT and _DAYS to quantity_limit, or undefined for no limit.
// 999 days: period null (decision D6). No column gives a unit (gap F3).
function quantityLimit(rel, kind, row, codes, errors) {
  const on = flag(rel, kind, row, 'QUANTITY_LIMIT_YN', codes, errors);
  const amount = row.cells[COL[kind].QUANTITY_LIMIT_AMOUNT].trim();
  const days = row.cells[COL[kind].QUANTITY_LIMIT_DAYS].trim();
  if (on === false) {
    if (amount !== '' || days !== '') errors.push(`${at(rel, kind, row, 'QUANTITY_LIMIT_YN')} with an amount "${amount}" or days "${days}"`);
    return undefined;
  }
  if (on !== true) return undefined;
  if (!/^(\d+(\.\d*)?|\.\d+)$/.test(amount)) { errors.push(`${at(rel, kind, row, 'QUANTITY_LIMIT_AMOUNT')} is not a number, with QUANTITY_LIMIT_YN on`); return undefined; }
  if (!/^\d+$/.test(days) || Number(days) < 1) { errors.push(`${at(rel, kind, row, 'QUANTITY_LIMIT_DAYS')} is not a whole number of days, with QUANTITY_LIMIT_YN on`); return undefined; }
  const n = Number(days);
  return { value: Number(amount), period: n === NO_PERIOD_DAYS ? null : `per_${n}_days` };
}

// A Basic Drugs Formulary row to a formulary item (spec section 5).
function basicItem(rel, row, errors) {
  const c = COL.basic;
  const ndc = row.cells[c.NDC];
  if (!/^\d{11}$/.test(ndc)) errors.push(`${at(rel, 'basic', row, 'NDC')} is not 11 digits`);
  return ordered({
    rxcui: rxcuiOf(rel, 'basic', row, errors),
    ndc,
    formulary_tier_id: tierId(rel, 'basic', row, 'TIER_LEVEL_VALUE', errors),
    covered: true,
    prior_authorization: flag(rel, 'basic', row, 'PRIOR_AUTHORIZATION_YN', YN, errors),
    step_therapy: flag(rel, 'basic', row, 'STEP_THERAPY_YN', YN, errors),
    quantity_limit: quantityLimit(rel, 'basic', row, YN, errors),
    coverage_basis: 'medicare_covered',
    negotiation_selected_drug: flag(rel, 'basic', row, 'SELECTED_DRUG_YN', YN, errors),
    source_references: [cite(rel, 'basic', row)],
  }, ITEM_KEYS);
}

// An Excluded Drugs Formulary row to a formulary item (spec section 6.1).
function excludedItem(rel, row, errors) {
  return ordered({
    rxcui: rxcuiOf(rel, 'excluded', row, errors),
    formulary_tier_id: tierId(rel, 'excluded', row, 'TIER', errors),
    covered: true,
    prior_authorization: flag(rel, 'excluded', row, 'PRIOR_AUTH_YN', YN, errors),
    step_therapy: flag(rel, 'excluded', row, 'STEP_THERAPY_YN', YN, errors),
    quantity_limit: quantityLimit(rel, 'excluded', row, QL_01, errors),
    coverage_basis: 'supplemental_mandatory',
    capped_benefit: flag(rel, 'excluded', row, 'CAPPED_BENEFIT_YN', YN, errors),
    source_references: [cite(rel, 'excluded', row)],
  }, ITEM_KEYS);
}

// ---- the formulary list (spec section 5) -----------------------------------------------------
function dataSource(rel, kinds) {
  return {
    source_type: 'cms_part_d_formulary',
    source_url: rel.zipUrl,
    import_timestamp: rel.manifest.downloaded,
    file_date: rel.posted,
    notes: `CMS Prescription Drug Plan Formulary and Pharmacy Network Information, release ${rel.release}: ` +
      kinds.map((k) => `${rel.names[k]}, SHA-256 ${rel.sha256[k]}`).join('; ') + '.',
  };
}

function formularyOrThrow(rel, id) {
  const f = rel.formularies.get(id);
  if (!f) throw new Error(`no FORMULARY_ID "${id}" in ${rel.names.basic}`);
  if (f.errors.length) throw new Error(`formulary ${id} cannot be read:\n  ${f.errors.join('\n  ')}`);
  if (Number(f.year) !== rel.contractYear) throw new Error(`formulary ${id}: CONTRACT_YEAR "${f.year}" is not the release's contract year ${rel.contractYear}`);
  return f;
}

// The list's items, in the file's order. Throws on any broken cell.
function listItems(rel, f) {
  const errors = [];
  const items = f.rows.map((row) => basicItem(rel, row, errors));
  if (errors.length) throw new Error(`formulary ${f.id} cannot be read:\n  ${errors.join('\n  ')}`);
  return items;
}

function buildList(rel, id) {
  const f = formularyOrThrow(rel, id);
  return {
    formulary_reference: {
      formulary_id: f.id,
      formulary_version: f.version,
      completeness: 'full_formulary',
      data_sources: [dataSource(rel, ['basic'])],
    },
    plan_year: Number(f.year),
    formulary_items: listItems(rel, f),
    source_references: [{ document: rel.zip, excerpt: `${rel.names.basic}, header: ${rel.headers.basic}` }],
    schema_version: SCHEMA_VERSION,
  };
}

// ---- the plan document (spec section 7) ------------------------------------------------------
// How the PBP importer cites a Defined Standard plan (docs/specs/pbp-part-d-mapping.md section 8).
const DEFINED_STANDARD = 'mrx_benefit_type "1" (Defined Standard)';
// A PBP importer error that only says the plan type is outside its scope is a refusal;
// any other error is an error.
const PBP_SCOPE = /is outside the importer's scope/;
const pbpRefusal = (errors) => errors.length > 0 && errors.every((e) => PBP_SCOPE.test(e));
const NETWORKS = { PREF: 'RETAIL_PREFERRED', NONPREF: 'RETAIL_STANDARD', MAIL_PREF: 'MAIL_ORDER_PREFERRED', MAIL_NONPREF: 'MAIL_ORDER_STANDARD' };
const SUPPLIES = { 1: '1M', 2: '3M', 4: '2M' };
const STAGES = { 1: 'INITIAL', 3: 'CATASTROPHIC' };
const plural = (n, one, many) => `${n.toLocaleString('en-US')} ${n === 1 ? one : many}`;

function planOrThrow(rel, key) {
  const p = rel.plans.get(key);
  if (!p) throw new Error(`no plan ${key} in ${rel.names.plan}`);
  if (p.errors.length) throw new Error(`${key} cannot be read:\n  ${p.errors.join('\n  ')}`);
  const sup = p.first.cells[COL.plan.PLAN_SUPPRESSED_YN];
  if (sup === 'Y') {
    const e = new Error(`${key} is refused: ${rel.names.plan} line ${p.first.line}, PLAN_SUPPRESSED_YN "Y": CMS publishes no drug data for a suppressed plan (Methodology; ${SPEC} section 11)`);
    e.refusal = true;
    throw e;
  }
  if (sup !== 'N') throw new Error(`${at(rel, 'plan', p.first, 'PLAN_SUPPRESSED_YN')} is not "Y" or "N"`);
  return p;
}

// The tiers of a Defined Standard plan, from its Beneficiary Cost rows (decision D4).
function tiersFromCost(rel, key, costRows, errors) {
  const c = COL.cost;
  const byTier = new Map();
  for (const row of costRows) {
    const t = row.cells[c.TIER];
    if (!/^\d{1,2}$/.test(t) || Number(t) < 1) { errors.push(`${at(rel, 'cost', row, 'TIER')} is not a tier number`); continue; }
    if (!byTier.has(Number(t))) byTier.set(Number(t), { raw: t, spec: new Set(), rows: 0 });
    const x = byTier.get(Number(t));
    x.spec.add(row.cells[c.TIER_SPECIALTY_YN]);
    x.rows++;
  }
  return [...byTier.keys()].sort((a, b) => a - b).map((n) => {
    const x = byTier.get(n);
    if (x.spec.size !== 1 || !['Y', 'N'].includes([...x.spec][0])) errors.push(`${rel.names.cost}: tier ${n} of ${key} has TIER_SPECIALTY_YN ${[...x.spec].map((v) => `"${v}"`).join(' and ')}`);
    const s = [...x.spec][0];
    const tier = { tier_id: `T${n}`, name: `Tier ${n}` };
    if (s === 'Y') tier.tier_code = 'specialty';
    tier.description = `${rel.names.cost}: TIER "${x.raw}", TIER_SPECIALTY_YN "${s}" on ${plural(x.rows, 'row', 'rows')}. ` +
      `The PBP files hold no tier rows for this plan, so the tier is read from the Beneficiary Cost file (${SPEC} section 7.3).`;
    return tier;
  });
}

// The plan's own items: an indication item replaces the list item of its drug, and the
// excluded drugs follow (spec sections 6 and 7.2).
function ownItems(rel, key, f, errors) {
  const cp = key.slice(0, 9);
  const ibcRows = rel.ibc.get(cp) || [];
  const byRx = new Map();
  for (const row of ibcRows) {
    const rx = rxcuiOf(rel, 'ibc', row, errors);
    if (!byRx.has(rx)) byRx.set(rx, []);
    byRx.get(rx).push(row);
  }
  const indication = [];
  for (const [rx, rows] of byRx) {
    const i = f.byRxcui.get(rx);
    if (i === undefined) { errors.push(`${at(rel, 'ibc', rows[0], 'RXCUI')} is not on formulary ${f.id}, the plan's Basic Drugs list`); continue; }
    const base = basicItem(rel, f.rows[i], errors);
    indication.push({
      index: i,
      item: ordered({
        ...base,
        covered: false,
        coverage_exceptions: rows.map((row) => ({ indication_code: null, indication_description: row.cells[COL.ibc.DISEASE], coverage_status: 'covered' })),
        source_references: [...base.source_references, ...rows.map((row) => cite(rel, 'ibc', row))],
      }, ITEM_KEYS),
    });
  }
  indication.sort((a, b) => a.index - b.index);
  const excluded = (rel.excluded.get(cp) || []).map((row) => excludedItem(rel, row, errors));
  return { indication, excluded, ibcRows: ibcRows.length };
}

// Builds a plan's document from the Medicare Advantage importer's document for it.
// mode 'whole': every item inline; mode 'shared': formulary_items_url names the list
// and formulary_items holds the plan's own items only. Returns { doc, comparison, facts }.
function buildPlanDocument(rel, key, pbpDoc, { mode = 'whole', items } = {}) {
  const p = planOrThrow(rel, key);
  const c = COL.plan;
  const cells = p.first.cells;
  const f = formularyOrThrow(rel, cells[c.FORMULARY_ID]);
  if (pbpDoc.plan_year !== undefined && pbpDoc.plan_year !== Number(f.year)) {
    throw new Error(`${key}: the PBP document's plan_year ${pbpDoc.plan_year} is not CONTRACT_YEAR "${f.year}" of formulary ${f.id}`);
  }
  const errors = [];
  const doc = JSON.parse(JSON.stringify(pbpDoc));
  const pharmacy = doc.pharmacy || {};
  const costRows = rel.cost.get(key) || [];
  if (costRows.length === 0) errors.push(`no rows for ${key} in ${rel.names.cost}`);
  const costTiers = [...new Set(costRows.map((r) => Number(r.cells[COL.cost.TIER])))].sort((a, b) => a - b).map((n) => `T${n}`);

  // Tiers: the PBP document's, proved against Beneficiary Cost, or a Defined Standard plan's from it (D4).
  // A plan is Defined Standard when the PBP document cites mrx_benefit_type "1"; any other plan
  // with no tiers is an error, not a plan to give the cost file's tiers to.
  let tiersFrom = 'pbp';
  if (!pharmacy.formulary_tiers || pharmacy.formulary_tiers.length === 0) {
    if (!(pbpDoc.source_references || []).some((r) => (r.excerpt || '').includes(DEFINED_STANDARD))) {
      errors.push(`${key}: the PBP document has no pharmacy.formulary_tiers and does not cite ${DEFINED_STANDARD}; the tiers are read from Beneficiary Cost for a Defined Standard plan only (${SPEC} section 7.3)`);
    }
    pharmacy.formulary_tiers = tiersFromCost(rel, key, costRows, errors);
    tiersFrom = 'beneficiary_cost';
  } else {
    const ids = pharmacy.formulary_tiers.map((t) => t.tier_id);
    if (ids.join() !== costTiers.join()) errors.push(`${key}: the Beneficiary Cost tiers ${costTiers.join(', ') || 'none'} are not the PBP document's tiers ${ids.join(', ')} (${SPEC} section 8)`);
  }
  const tierIds = new Set(pharmacy.formulary_tiers.map((t) => t.tier_id));

  const listed = items || listItems(rel, f);
  const own = ownItems(rel, key, f, errors);
  let formularyItems;
  if (mode === 'whole') {
    formularyItems = listed.slice();
    for (const x of own.indication) formularyItems[x.index] = x.item;
    formularyItems.push(...own.excluded);
  } else {
    formularyItems = [...own.indication.map((x) => x.item), ...own.excluded];
  }
  for (const it of [...listed, ...own.indication.map((x) => x.item), ...own.excluded]) {
    if (it.formulary_tier_id && !tierIds.has(it.formulary_tier_id)) {
      errors.push(`${key}: drug ${it.rxcui} is on ${it.formulary_tier_id}, which is not a tier of the plan (${[...tierIds].join(', ')}): ${it.source_references[0].excerpt}`);
    }
  }
  // A stand-alone drug plan's premium: PREMIUM, which no PBP file holds (decided 2026-11-11,
  // finding N1 of docs/specs/partd-formulary/stop-2.md). A Medicare Advantage plan's PREMIUM is the
  // Part D part of its premium and is not written here.
  const standAlone = key[0] === 'S';
  const premiumCell = cells[c.PREMIUM];
  if (!/^\d+\.\d{2}$/.test(premiumCell)) errors.push(`${at(rel, 'plan', p.first, 'PREMIUM')} is not an amount in dollars and cents`);
  if (standAlone && doc.premium) errors.push(`${key}: the PBP document already has a premium, and a stand-alone drug plan's comes from PREMIUM only`);
  if (errors.length) throw new Error(`${key} cannot be imported:\n  ${errors.join('\n  ')}`);
  // A Medicare Advantage plan's PREMIUM is the Part D part of its premium: premium.drug_amount
  // (v1.2.0 draft 9), beside the PBP importer's amount, which leaves that part out. With no PBP
  // premium there is no amount to put it beside, and it is quoted only.
  if (standAlone) doc.premium = { amount: Number(premiumCell), currency: 'USD', period: 'per_month' };
  else if (doc.premium) doc.premium = ordered({ ...doc.premium, drug_amount: Number(premiumCell) }, PREMIUM_KEYS);

  const kinds = ['plan', 'basic', 'cost', ...(own.excluded.length ? ['excluded'] : []), ...(own.ibcRows ? ['ibc'] : [])];
  const reference = {
    formulary_id: f.id,
    formulary_version: f.version,
    formulary_items_url: mode === 'shared' ? `../formularies/${f.id}.json` : undefined,
    completeness: 'full_formulary',
    source_plan_identifiers: { cms_contract_id: cells[c.CONTRACT_ID], cms_pbp_id: cells[c.PLAN_ID] },
    data_sources: [dataSource(rel, kinds)],
  };
  if (reference.formulary_items_url === undefined) delete reference.formulary_items_url;
  pharmacy.formulary_items = formularyItems.length ? formularyItems : undefined;
  pharmacy.formulary_reference = reference;
  doc.pharmacy = ordered(pharmacy, PHARMACY_KEYS);

  // Root citations, after the PBP importer's (spec section 7.2).
  const where = mode === 'shared' ? `in the formulary list that pharmacy.formulary_reference.formulary_items_url names` : 'in pharmacy.formulary_items';
  const refs = [
    { document: rel.zip, excerpt: `${rel.names.plan}, header: ${rel.headers.plan}. ` + (p.rows === 1 ? `The plan's row: ${p.first.raw}`
      : `The plan's first row of ${p.rows.toLocaleString('en-US')}, 1 per county, which all give the same FORMULARY_ID, PREMIUM, DEDUCTIBLE, SNP and PLAN_NAME: ${p.first.raw}`) },
    { document: rel.zip, excerpt: `${rel.names.basic}: FORMULARY_ID "${f.id}", FORMULARY_VERSION "${f.version}", CONTRACT_YEAR "${f.year}", ${plural(f.rows.length, 'row', 'rows')}, 1 item each, ${where}, each quoting its row; header: ${rel.headers.basic}` },
  ];
  if (own.indication.length) {
    refs.push({ document: rel.zip, excerpt: `${rel.names.ibc}, header: ${rel.headers.ibc}. ${plural(own.ibcRows, 'row', 'rows')} for CONTRACT_ID "${cells[c.CONTRACT_ID]}", PLAN_ID "${cells[c.PLAN_ID]}": ${plural(own.indication.length, 'drug is', 'drugs are')} on the formulary for the listed indications only, so ${own.indication.length === 1 ? 'its item' : 'each one\'s item'} in pharmacy.formulary_items has covered false and 1 coverage_exceptions entry per indication, and replaces the list's item (${SPEC} section 6.2).` });
  }
  if (own.excluded.length) {
    refs.push({ document: rel.zip, excerpt: `${rel.names.excluded}, header: ${rel.headers.excluded}. ${plural(own.excluded.length, 'row', 'rows')} for CONTRACT_ID "${cells[c.CONTRACT_ID]}", PLAN_ID "${cells[c.PLAN_ID]}", 1 item each in pharmacy.formulary_items with coverage_basis "supplemental_mandatory": drugs Part D excludes that the plan covers as a supplemental benefit (${SPEC} section 6.1).` });
  }
  refs.push({
    document: rel.zip,
    excerpt: `${rel.names.cost}: ${plural(costRows.length, 'row', 'rows')} for ${key}, tiers ${costTiers.map((t) => t.slice(1)).join(', ')}. ` + (tiersFrom === 'beneficiary_cost'
      ? `The PBP files hold no tier rows for this plan (a Defined Standard plan), so pharmacy.formulary_tiers is read from these rows; no cost share is written from them (${SPEC} section 7.3).`
      : `The same tiers as pharmacy.formulary_tiers, which the PBP files give; the file's cost cells are compared with the Part D benefits and not written (${SPEC} sections 7.3 and 8).`),
  });
  refs.splice(1, 0, { document: rel.zip, excerpt: `${rel.names.plan}: PREMIUM "${premiumCell}", the layout's "Monthly premium amount". ` + (standAlone
    ? `Written as premium.amount in USD with period per_month. The PBP files hold no premium for a stand-alone drug plan (docs/specs/pbp-part-d-mapping.md section 4), so this is the document's only premium (${SPEC} section 7.2).`
    : doc.premium
      ? `For a Medicare Advantage plan it is the Part D part of the monthly premium, written as premium.drug_amount; premium.amount, from the PBP files, is the rest, and the monthly plan premium is their sum (${SPEC} section 7.2).`
      : `For a Medicare Advantage plan it is the Part D part of the monthly premium. Not written: the PBP document has no premium for it to complete (${SPEC} section 7.2).`) });
  doc.source_references = [...(doc.source_references || []), ...refs];
  return {
    doc: ordered(doc, ROOT_KEYS),
    comparison: compare(rel, key, pbpDoc, p, costRows),
    facts: { formulary: f.id, tiersFrom, excluded: own.excluded.length, capped: own.excluded.filter((x) => x.capped_benefit).length, indication: own.indication.length },
  };
}
// ---- checks that write nothing (spec section 8, decision D7) ---------------------------------
function compare(rel, key, pbpDoc, p, costRows) {
  const c = COL.plan;
  const cells = p.first.cells;
  // PREMIUM is not compared: for a Medicare Advantage plan it is the Part D part of the premium,
  // and the PBP importer's premium is the Part C part (stop-2.md, finding N1). Both are kept for the report.
  const out = { compared: 0, matched: 0, notCompared: 0, differences: [],
    premium: { file: Number(cells[c.PREMIUM]), pbp: pbpDoc.premium && typeof pbpDoc.premium.amount === 'number' ? pbpDoc.premium.amount : null } };
  const diff = (kind, detail) => out.differences.push({ kind, detail });
  const check = (ok, kind, detail) => { out.compared++; if (ok) out.matched++; else diff(kind, detail); };
  const rx = pbpDoc.pharmacy || {};
  if (rx.deductible && typeof rx.deductible.amount === 'number') {
    check(Number(cells[c.DEDUCTIBLE]) === rx.deductible.amount, 'deductible', `DEDUCTIBLE "${cells[c.DEDUCTIBLE]}", PBP pharmacy.deductible.amount ${rx.deductible.amount}`);
  } else out.notCompared++;
  check(cells[c.PLAN_NAME] === pbpDoc.plan_name, 'plan_name', `PLAN_NAME "${cells[c.PLAN_NAME]}", PBP plan_name "${pbpDoc.plan_name}"`);

  const tiers = new Map((rx.formulary_tiers || []).map((t) => [t.tier_id, t]));
  if (tiers.size === 0) { out.notCompared += costRows.length; return out; }
  const cc = COL.cost;
  const ded = rx.deductible && rx.deductible.amount > 0 ? rx.deductible : null;
  const tierFacts = new Map();
  for (const row of costRows) {
    const t = `T${Number(row.cells[cc.TIER])}`;
    if (!tierFacts.has(t)) tierFacts.set(t, { spec: row.cells[cc.TIER_SPECIALTY_YN], ded: row.cells[cc.DED_APPLIES_YN] });
  }
  for (const [t, x] of tierFacts) {
    const tier = tiers.get(t);
    if (!tier) continue;
    check((x.spec === 'Y') === (tier.tier_code === 'specialty'), 'specialty', `${key} ${t}: TIER_SPECIALTY_YN "${x.spec}", PBP tier_code ${tier.tier_code ? `"${tier.tier_code}"` : 'absent'}`);
    const applies = !!ded && (!ded.applies_to_tiers || ded.applies_to_tiers.includes(t));
    check((x.ded === 'Y') === applies, 'deductible_applies', `${key} ${t}: DED_APPLIES_YN "${x.ded}", PBP deductible ${ded ? `${ded.amount} on ${ded.applies_to_tiers ? ded.applies_to_tiers.join(', ') : 'every tier'}` : 'none'}`);
  }

  const benefits = (pbpDoc.benefits || []).filter((b) => b.benefit_type === 'pharmacy');
  for (const row of costRows) {
    const level = row.cells[cc.COVERAGE_LEVEL];
    const stage = STAGES[level];
    const supply = SUPPLIES[row.cells[cc.DAYS_SUPPLY]];
    if (!stage || !supply) { out.notCompared++; continue; }
    const t = `T${Number(row.cells[cc.TIER])}`;
    for (const [ch, net] of Object.entries(NETWORKS)) {
      const type = row.cells[cc[`COST_TYPE_${ch}`]];
      const amt = Number(row.cells[cc[`COST_AMT_${ch}`]]);
      const min = Number(row.cells[cc[`COST_MIN_AMT_${ch}`]]) || 0;
      const max = Number(row.cells[cc[`COST_MAX_AMT_${ch}`]]) || 0;
      const where = `${key} ${t} ${net} ${supply} ${stage}`;
      const b = stage === 'CATASTROPHIC'
        ? benefits.find((x) => x.formulary_tier_id === t && x.coverage_stage_id === 'CATASTROPHIC')
        : benefits.find((x) => x.formulary_tier_id === t && x.coverage_stage_id === stage && x.pharmacy_network_id === net && x.benefit_id.includes(`_${supply}_`));
      if (type === '0') {
        if (stage !== 'CATASTROPHIC') check(!b, 'not_offered', `${where}: COST_TYPE_${ch} "0" (not offered), and the PBP document has ${b ? b.benefit_id : 'no benefit'}`);
        continue;
      }
      if (type !== '1' && type !== '2') { check(false, 'cost_type', `${where}: COST_TYPE_${ch} "${type}" is not 0, 1 or 2`); continue; }
      if (!b) { check(false, 'no_benefit', `${where}: COST_TYPE_${ch} "${type}", COST_AMT_${ch} "${row.cells[cc[`COST_AMT_${ch}`]]}", and the PBP document has no benefit`); continue; }
      const steps = (b.network_cost_shares || []).flatMap((r) => r.cost_shares || []);
      // $0 is $0: a 0% coinsurance in 1 source and a $0 copay in the other say the member pays nothing.
      const zero = (s) => (s.type === 'copay' && s.amount === 0) || (s.type === 'coinsurance' && s.rate === 0);
      const hit = steps.some((s) => ((type === '1' ? s.type === 'copay' && s.amount === amt : s.type === 'coinsurance' && s.rate === amt) || (amt === 0 && zero(s))) &&
        (min === 0 || s.min_amount === min) && (max === 0 || s.max_amount === max));
      check(hit, 'cost_value', `${where}: COST_TYPE_${ch} "${type}", COST_AMT "${row.cells[cc[`COST_AMT_${ch}`]]}", MIN "${row.cells[cc[`COST_MIN_AMT_${ch}`]]}", MAX "${row.cells[cc[`COST_MAX_AMT_${ch}`]]}"; PBP ${b.benefit_id}: ` +
        steps.map((s) => `${s.type} ${s.amount !== undefined ? s.amount : s.rate}${s.min_amount !== undefined ? ` min ${s.min_amount}` : ''}${s.max_amount !== undefined ? ` max ${s.max_amount}` : ''}`).join('; '));
    }
  }
  return out;
}

// ---- schema check (local files, no network) ---------------------------------------------------
let validators = null;
function validatorsOnce() {
  if (validators) return validators;
  const Ajv2020 = require('ajv/dist/2020');
  const ajv = new Ajv2020({ allErrors: true, strict: false });
  try { require('ajv-formats')(ajv); } catch (e) { /* optional */ }
  const read = (f) => JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'schema', 'v' + SCHEMA_VERSION, f), 'utf8'));
  ajv.addSchema(read('benefit-plan.schema.json'));
  const plan = ajv.getSchema('https://benefitplanstandard.org/schema/v1.2.0/benefit-plan.schema.json');
  const list = ajv.compile(read('formulary.schema.json'));
  const run = (v) => (doc) => (v(doc) ? [] : v.errors.map((e) => `${e.instancePath || '(root)'} ${e.message}`));
  validators = { plan: run(plan), list: run(list) };
  return validators;
}

function serialize(doc) {
  return JSON.stringify(doc, null, 2) + '\n';
}

// ---- the count report (spec section 10) -----------------------------------------------------
function formularyCounts(rel) {
  const users = new Map();
  for (const p of rel.plans.values()) {
    if (p.first.cells[COL.plan.PLAN_SUPPRESSED_YN] !== 'N') continue;
    const id = p.first.cells[COL.plan.FORMULARY_ID];
    users.set(id, (users.get(id) || 0) + 1);
  }
  const c = COL.basic;
  return [...rel.formularies.values()].map((f) => {
    const n = (col, v) => f.rows.filter((r) => r.cells[c[col]] === v).length;
    return {
      formulary_id: f.id, formulary_version: f.version, plans: users.get(f.id) || 0, drugs: f.rows.length,
      prior_authorization: n('PRIOR_AUTHORIZATION_YN', 'Y'), step_therapy: n('STEP_THERAPY_YN', 'Y'),
      quantity_limit: n('QUANTITY_LIMIT_YN', 'Y'), quantity_limit_999_days: n('QUANTITY_LIMIT_DAYS', String(NO_PERIOD_DAYS)),
      negotiation_selected_drug: n('SELECTED_DRUG_YN', 'Y'), tiers: [...new Set(f.rows.map((r) => Number(r.cells[c.TIER_LEVEL_VALUE])))].sort((a, b) => a - b).join(','),
    };
  });
}

function countReport(rel) {
  const formularies = formularyCounts(rel);
  const sum = (k) => formularies.reduce((a, f) => a + f[k], 0);
  const plans = [...rel.plans.values()];
  const suppressed = plans.filter((p) => p.first.cells[COL.plan.PLAN_SUPPRESSED_YN] === 'Y').map((p) => p.key);
  return {
    release: rel.release,
    contract_year: rel.contractYear,
    files: Object.fromEntries(Object.keys(FILES).map((k) => [k, { name: rel.names[k], sha256: rel.sha256[k] }])),
    plans: { in_plan_information: plans.length, suppressed: suppressed.length, suppressed_plans: suppressed },
    totals: {
      formularies: formularies.length, drug_rows: sum('drugs'), prior_authorization: sum('prior_authorization'), step_therapy: sum('step_therapy'),
      quantity_limit: sum('quantity_limit'), quantity_limit_999_days: sum('quantity_limit_999_days'), negotiation_selected_drug: sum('negotiation_selected_drug'),
      excluded_drug_rows: [...rel.excluded.values()].reduce((a, r) => a + r.length, 0), excluded_drug_plans: rel.excluded.size,
      indication_rows: [...rel.ibc.values()].reduce((a, r) => a + r.length, 0), indication_plans: rel.ibc.size,
    },
    formularies,
  };
}

// ---- --all (spec section 4) ---------------------------------------------------------------------
async function runAll({ dataDir = DATA_DIR, pbpDataDir = PBP_DATA_DIR, release, outDir, batch = 400, log = () => {} }) {
  for (const sub of ['formularies', 'plans']) {
    const d = path.join(outDir, sub);
    if (fs.existsSync(d) && fs.readdirSync(d).some((f) => f.endsWith('.json'))) {
      throw new Error(`${d} already holds documents: --all writes into empty folders, so that no document of an earlier run is left among this run's`);
    }
  }
  const rel = await loadRelease({ dataDir, release });
  const v = validatorsOnce();
  const report = countReport(rel);
  fs.mkdirSync(path.join(outDir, 'formularies'), { recursive: true });
  fs.mkdirSync(path.join(outDir, 'plans'), { recursive: true });
  const itemsOf = new Map();
  for (const id of [...rel.formularies.keys()].sort()) {
    const list = buildList(rel, id);
    const errs = v.list(list);
    if (errs.length) throw new Error(`formulary ${id} fails formulary.schema.json:\n  ${errs.slice(0, 10).join('\n  ')}`);
    fs.writeFileSync(path.join(outDir, 'formularies', `${id}.json`), serialize(list));
    itemsOf.set(id, list.formulary_items);
  }
  log(`wrote ${itemsOf.size} formulary lists`);
  const keys = [...rel.plans.keys()].sort();
  const result = { built: 0, refused: [], errors: [], tiers_from_beneficiary_cost: 0, excluded_items: 0, capped_benefit_items: 0, indication_items: 0 };
  const cmp = { plans: 0, compared: 0, matched: 0, not_compared: 0, by_kind: {}, samples: {},
    premium: { no_pbp_premium: 0, both_zero: 0, equal_above_zero: 0, file_above_zero_pbp_zero: 0, file_zero_pbp_above_zero: 0, both_above_zero_differ: 0 } };
  const diffFile = fs.openSync(path.join(outDir, 'differences.jsonl'), 'w');
  const plansFile = fs.openSync(path.join(outDir, 'plans.jsonl'), 'w');
  const premiumKind = ({ file, pbp }) => (pbp === null ? 'no_pbp_premium' : file === pbp ? (file === 0 ? 'both_zero' : 'equal_above_zero')
    : pbp === 0 ? 'file_above_zero_pbp_zero' : file === 0 ? 'file_zero_pbp_above_zero' : 'both_above_zero_differ');
  for (let i = 0; i < keys.length; i += batch) {
    const slice = keys.slice(i, i + batch).filter((k) => {
      try { planOrThrow(rel, k); return true; } catch (e) { (e.refusal ? result.refused : result.errors).push({ plan: k, reason: e.message }); return false; }
    });
    let loaded;
    try {
      loaded = await pbp.loadPlans({ dataDir: pbpDataDir, year: rel.contractYear, plans: slice });
    } catch (e) {
      // A plan missing from the PBP files stops the batch; build it plan by plan to find it.
      loaded = new Map();
      for (const k of slice) {
        try { const one = await pbp.loadPlan({ dataDir: pbpDataDir, year: rel.contractYear, plan: k }); loaded.set(k, one); } catch (e2) { result.errors.push({ plan: k, reason: `PBP files: ${e2.message}` }); }
      }
    }
    for (const k of slice) {
      const got = loaded.get(k);
      if (!got) continue;
      const built = pbp.buildDocument(got.rows, got.source);
      if (built.errors.length) {
        const refusal = pbpRefusal(built.errors);
        (refusal ? result.refused : result.errors).push({ plan: k, reason: `the PBP importer ${refusal ? 'refuses' : 'cannot build'} the plan: ${built.errors.join(' | ')}` });
        continue;
      }
      try {
        const p = rel.plans.get(k);
        const { doc, comparison, facts } = buildPlanDocument(rel, k, built.doc, { mode: 'shared', items: itemsOf.get(p.first.cells[COL.plan.FORMULARY_ID]) });
        const errs = v.plan(doc);
        if (errs.length) throw new Error(`fails benefit-plan.schema.json:\n  ${errs.slice(0, 10).join('\n  ')}`);
        fs.writeFileSync(path.join(outDir, 'plans', `${k}.json`), serialize(doc));
        result.built++;
        if (facts.tiersFrom === 'beneficiary_cost') result.tiers_from_beneficiary_cost++;
        result.excluded_items += facts.excluded;
        result.capped_benefit_items += facts.capped;
        result.indication_items += facts.indication;
        cmp.plans++; cmp.compared += comparison.compared; cmp.matched += comparison.matched; cmp.not_compared += comparison.notCompared;
        cmp.premium[premiumKind(comparison.premium)]++;
        fs.writeSync(plansFile, JSON.stringify({ plan: k, formulary: facts.formulary, tiers_from: facts.tiersFrom, excluded_items: facts.excluded,
          capped_benefit_items: facts.capped, indication_items: facts.indication, compared: comparison.compared, matched: comparison.matched,
          differences: comparison.differences.length, premium_file: comparison.premium.file, premium_pbp: comparison.premium.pbp }) + '\n');
        for (const d of comparison.differences) {
          fs.writeSync(diffFile, JSON.stringify({ plan: k, ...d }) + '\n');
          cmp.by_kind[d.kind] = (cmp.by_kind[d.kind] || 0) + 1;
          (cmp.samples[d.kind] = cmp.samples[d.kind] || []);
          if (cmp.samples[d.kind].length < 15) cmp.samples[d.kind].push(d.detail);
        }
      } catch (e) {
        result.errors.push({ plan: k, reason: e.message });
      }
    }
    log(`${Math.min(i + batch, keys.length)} of ${keys.length} plans: ${result.built} built, ${result.refused.length} refused, ${result.errors.length} errors`);
  }
  fs.closeSync(diffFile);
  fs.closeSync(plansFile);
  report.run = result;
  report.comparison = cmp;
  fs.writeFileSync(path.join(outDir, 'report.json'), serialize(report));
  return report;
}

