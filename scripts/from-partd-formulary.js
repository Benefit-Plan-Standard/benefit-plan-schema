// Builds the 5 golden plans in the shared layout and their lists; returns [{ file, text }]
// with paths relative to examples/partd-formulary/.
async function buildGolden({ dataDir = DATA_DIR, pbpDataDir = PBP_DATA_DIR } = {}) {
  const rel = await loadRelease({ dataDir, release: GOLDEN_RELEASE });
  const v = validatorsOnce();
  const out = [];
  const lists = new Map();
  for (const g of GOLDEN) {
    const p = planOrThrow(rel, g.plan);
    const id = p.first.cells[COL.plan.FORMULARY_ID];
    if (!lists.has(id)) {
      const list = buildList(rel, id);
      const errs = v.list(list);
      if (errs.length) throw new Error(`formulary ${id} fails formulary.schema.json:\n  ${errs.join('\n  ')}`);
      lists.set(id, list);
      out.push({ file: `formularies/${id}.json`, text: serialize(list) });
    }
    const { doc } = buildPlanDocument(rel, g.plan, await pbpDocument(pbpDataDir, rel.contractYear, g.plan), { mode: 'shared', items: lists.get(id).formulary_items });
    const errs = v.plan(doc);
    if (errs.length) throw new Error(`${g.plan} fails benefit-plan.schema.json:\n  ${errs.join('\n  ')}`);
    out.push({ file: `plans/${g.plan}.json`, text: serialize(doc) });
  }
  return out;
}

// Copies the header and the wanted records of each file, byte for byte (latin1 maps each
// byte to 1 character and back), under the same names.
async function cutFile(src, dst, keep) {
  const out = fs.openSync(dst, 'w');
  let carry = '';
  let first = true;
  let kept = 0;
  const take = (rec) => {
    if (first) { first = false; fs.writeSync(out, rec + '\r\n', null, 'latin1'); return; }
    if (rec !== '' && keep(rec.split('|'))) { fs.writeSync(out, rec + '\r\n', null, 'latin1'); kept++; }
  };
  for await (const chunk of fs.createReadStream(src, { highWaterMark: 1 << 20 })) {
    const parts = (carry + chunk.toString('latin1')).split('\r\n');
    carry = parts.pop();
    for (const p of parts) take(p);
  }
  if (carry !== '') take(carry);
  fs.closeSync(out);
  return kept;
}

async function writeFixtures({ dataDir = DATA_DIR, fixtureDir = FIXTURE_DIR } = {}) {
  const rel = await loadRelease({ dataDir, release: GOLDEN_RELEASE });
  const { find, manifest } = releaseDir(dataDir, GOLDEN_RELEASE);
  const plans = [...GOLDEN, ...EDGE].map((g) => g.plan);
  const cps = new Set(plans.map((k) => k.slice(0, 9)));
  const fidOf = (k) => planOrThrow(rel, k).first.cells[COL.plan.FORMULARY_ID];
  const whole = new Set(GOLDEN.map((g) => fidOf(g.plan)));
  const partRx = new Map();
  for (const e of EDGE) {
    const id = fidOf(e.plan);
    if (whole.has(id)) continue;
    const f = rel.formularies.get(id);
    const want = partRx.get(id) || new Set();
    f.rows.slice(0, EDGE_FIRST_ROWS).forEach((r) => want.add(r.cells[COL.basic.RXCUI].trim()));
    for (const kind of ['excluded', 'ibc']) (rel[kind].get(e.plan.slice(0, 9)) || []).forEach((r) => want.add(r.cells[COL[kind].RXCUI].trim()));
    partRx.set(id, want);
  }
  const outDir = path.join(fixtureDir, GOLDEN_RELEASE);
  fs.mkdirSync(outDir, { recursive: true });
  const planKey = (f) => `${f[0]}-${f[1]}-${f[2]}`;
  const keep = {
    plan: (f) => plans.includes(planKey(f)),
    basic: (f) => whole.has(f[0]) || (partRx.has(f[0]) && partRx.get(f[0]).has(f[3].trim())),
    excluded: (f) => cps.has(`${f[0]}-${f[1]}`),
    cost: (f) => plans.includes(planKey(f)),
    ibc: (f) => cps.has(`${f[0]}-${f[1]}`),
  };
  const records = {};
  for (const kind of Object.keys(FILES)) {
    const src = find(FILES[kind]);
    records[path.basename(src)] = await cutFile(src, path.join(outDir, path.basename(src)), keep[kind]);
  }
  const fixtureManifest = {
    description: `Rows cut from the CMS Prescription Drug Plan Formulary and Pharmacy Network Information file, release ${GOLDEN_RELEASE}, ` +
      'by node scripts/from-partd-formulary.js --write-fixtures, for scripts/from-partd-formulary.test.js. Each file holds the original header line ' +
      'and the kept records, byte for byte. The golden plans keep every row of their formularies; the edge plans keep the first ' +
      `${EDGE_FIRST_ROWS} rows of theirs and every row whose drug is on the plan's Excluded Drugs or Indication Based Coverage rows. ` +
      'downloaded, urls and sha256 are those of the full files, which the documents cite.',
    downloaded: manifest.downloaded,
    release_label: GOLDEN_RELEASE,
    urls: manifest.urls,
    zip_last_modified: manifest.zip_last_modified,
    golden_plans: GOLDEN.map((g) => g.plan),
    edge_plans: EDGE.map((g) => g.plan),
    records,
    sha256: Object.fromEntries(Object.values(rel.names).map((n) => [n, manifest.sha256[n]])),
  };
  fs.writeFileSync(path.join(outDir, 'download.json'), JSON.stringify(fixtureManifest, null, 2) + '\n');
  return [`wrote ${path.relative(REPO_ROOT, outDir)}: ${Object.keys(records).length} files, ${Object.values(records).reduce((a, b) => a + b, 0)} records`];
}

// ---- CLI -------------------------------------------------------------------------------------------
async function main(argv) {
  const opt = {};
  for (let i = 0; i < argv.length; i++) {
    const x = argv[i];
    if (x === '--release') opt.release = argv[++i];
    else if (x === '--plan') opt.plan = argv[++i];
    else if (x === '--formulary') opt.formulary = argv[++i];
    else if (x === '--all') opt.all = true;
    else if (x === '--report') opt.report = true;
    else if (x === '--out' || x === '-o') opt.out = argv[++i];
    else if (x === '--out-dir') opt.outDir = argv[++i];
    else if (x === '--data') opt.dataDir = path.resolve(argv[++i]);
    else if (x === '--pbp-data') opt.pbpDataDir = path.resolve(argv[++i]);
    else if (x === '--write-golden') opt.writeGolden = true;
    else if (x === '--write-fixtures') opt.writeFixtures = true;
    else if (x === '-h' || x === '--help') {
      console.log('usage: node scripts/from-partd-formulary.js --release <YYYY_YYYYMMDD> --plan <H1234-567-000> [--out <file>]\n' +
        '       node scripts/from-partd-formulary.js --release <YYYY_YYYYMMDD> --formulary <FORMULARY_ID> [--out <file>]\n' +
        '       node scripts/from-partd-formulary.js --release <YYYY_YYYYMMDD> --all --out-dir <dir>\n' +
        '       node scripts/from-partd-formulary.js --release <YYYY_YYYYMMDD> --report [--out <file>]\n' +
        '       node scripts/from-partd-formulary.js --write-golden      regenerate examples/partd-formulary/ from the full files\n' +
        '       node scripts/from-partd-formulary.js --write-fixtures    re-cut test/fixtures/partd-formulary/ from the full files\n' +
        '       options: --data <dir> (default data/partd-formulary), --pbp-data <dir> (default data/pbp)');
      return 0;
    } else {
      console.error(`error: unknown argument "${x}"`);
      return 1;
    }
  }
  const dataDir = opt.dataDir || DATA_DIR;
  const pbpDataDir = opt.pbpDataDir || PBP_DATA_DIR;
  const emit = (text) => { if (opt.out) fs.writeFileSync(opt.out, text); else process.stdout.write(text); };
  try {
    if (opt.writeGolden || opt.writeFixtures) {
      if (opt.writeFixtures) for (const line of await writeFixtures({ dataDir })) console.log(line);
      if (opt.writeGolden) {
        const built = await buildGolden({ dataDir, pbpDataDir });
        for (const { file, text } of built) {
          fs.mkdirSync(path.dirname(path.join(EXAMPLES_DIR, file)), { recursive: true });
          fs.writeFileSync(path.join(EXAMPLES_DIR, file), text);
          console.log(`wrote examples/partd-formulary/${file}`);
        }
        for (const sub of ['formularies', 'plans']) {
          for (const f of fs.readdirSync(path.join(EXAMPLES_DIR, sub)).filter((x) => x.endsWith('.json'))) {
            if (!built.some((b) => b.file === `${sub}/${f}`)) console.error(`warning: examples/partd-formulary/${sub}/${f} is not a golden document any more; remove it`);
          }
        }
      }
      return 0;
    }
    if (!opt.release) throw new Error('--release is required, as 2027_20261008');
    if (opt.all) {
      if (!opt.outDir) throw new Error('--all needs --out-dir <dir>');
      if (opt.out) throw new Error('--all writes into --out-dir, and takes no --out');
      const r = await runAll({ dataDir, pbpDataDir, release: opt.release, outDir: opt.outDir, log: (s) => console.error(s) });
      console.log(`${r.run.built} plans built, ${r.run.refused.length} refused, ${r.run.errors.length} errors; ${r.totals.formularies} lists; report: ${path.join(opt.outDir, 'report.json')}`);
      return r.run.errors.length ? 1 : 0;
    }
    const rel = await loadRelease({ dataDir, release: opt.release });
    if (opt.report) { emit(serialize(countReport(rel))); return 0; }
    if (opt.formulary) {
      const list = buildList(rel, opt.formulary);
      const errs = validatorsOnce().list(list);
      if (errs.length) throw new Error(`output fails formulary.schema.json:\n  ${errs.join('\n  ')}`);
      emit(serialize(list));
      return 0;
    }
    if (!opt.plan) throw new Error('give --plan, --formulary, --all or --report');
    pbp.parseKey(opt.plan);
    planOrThrow(rel, opt.plan);
    const { doc } = buildPlanDocument(rel, opt.plan, await pbpDocument(pbpDataDir, rel.contractYear, opt.plan), { mode: 'whole' });
    const errs = validatorsOnce().plan(doc);
    if (errs.length) throw new Error(`output fails benefit-plan.schema.json:\n  ${errs.join('\n  ')}`);
    emit(serialize(doc));
    return 0;
  } catch (e) {
    console.error('error: ' + e.message);
    return 1;
  }
}

